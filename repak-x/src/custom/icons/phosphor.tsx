// repakxtra: Lucide's icon names drawn with Phosphor bold. While set.ts says 'phosphor', vitePlugin.ts points every
// `lucide-react` import here, so no component changes its imports. A name not listed below falls through to Lucide.
import { forwardRef } from 'react'
import type { LucideProps } from 'lucide-react'
import * as P from '@phosphor-icons/react'

export * from 'lucide-react' // unlisted names and types stay Lucide's (this file's own import reaches the real package)

/** A Phosphor icon that takes Lucide's props: 24px by default like Lucide, bold, or fill when Lucide was asked for a
 *  filled shape (fill="currentColor"). Keeps the `lucide` class the app's CSS sizes icons by, plus `ph`. */
const ph = (Icon: P.Icon) =>
  forwardRef<SVGSVGElement, LucideProps>(({ size = 24, strokeWidth: _w, absoluteStrokeWidth: _a, fill, className, ...rest }, ref) => (
    <Icon ref={ref} size={size} weight={fill && fill !== 'none' ? 'fill' : 'bold'} className={`lucide ph${className ? ` ${className}` : ''}`} {...(rest as P.IconProps)} />
  ))

